using Qowaiv.CodeGeneration;
using Qowaiv.CodeGeneration.Syntax;
using Qowaiv.TestTools.Resx;
using System.Xml.Linq;

namespace Globalization.Countries_generation;

[Explicit]
public class Generates
{
    private static readonly CultureInfo[] Supported =
        [
            CultureInfo.InvariantCulture,
            TestCultures.de,
            TestCultures.es,
            TestCultures.fr,
            TestCultures.it,
            TestCultures.nl,
            TestCultures.pt,
            TestCultures.ru,
            TestCultures.ja,
            TestCultures.zh,
            TestCultures.zh_HK,
            TestCultures.zh_TW,
            TestCultures.ar
        ];

    [Test]
    public void Resources()
    {
        var unknowns = XResourceCollection.Load(new("../../../../../src/Qowaiv"), "UnknownLabels");

        using var reader = new FileInfo("../../../../../Countries.md").OpenText();

        var entries = CountryEntry.Read(reader).ToArray();

        var resources = new XResourceCollection();

        resources.Invariant.AddDisplay("ZZ", nameof(Unknown));
        foreach (var culture in Supported.Skip(1))
        {
            resources[culture].AddDisplay("ZZ", unknowns.TryGetValue("Values", culture)!.Split(';')[0]);
        }

        foreach (var e in entries)
        {
            // It is in there, but there is no better source.
            resources.Invariant.AddKey(e.Name, "CallingCode", Country.Parse(e.Name).CallingCode);
            resources.Invariant.AddDisplay(e.Name, e.En);
            if (e.En != e.De) resources[TestCultures.de].AddDisplay(e.Name, e.De);
            if (e.En != e.Es) resources[TestCultures.es].AddDisplay(e.Name, e.Es);
            if (e.En != e.Fr) resources[TestCultures.fr].AddDisplay(e.Name, e.Fr);
            if (e.En != e.It) resources[TestCultures.it].AddDisplay(e.Name, e.It);
            if (e.En != e.Nl) resources[TestCultures.nl].AddDisplay(e.Name, e.Nl);
            if (e.En != e.Pt) resources[TestCultures.pt].AddDisplay(e.Name, e.Pt);
            if (e.En != e.Ru) resources[TestCultures.ru].AddDisplay(e.Name, e.Ru);
            if (e.En != e.Ja) resources[TestCultures.ja].AddDisplay(e.Name, e.Ja);
            if (e.En != e.Zh) resources[TestCultures.zh].AddDisplay(e.Name, e.Zh);
            if (e.En != e.Ar) resources[TestCultures.ar].AddDisplay(e.Name, e.Ar);
            if (e.Zh != e.Zh_HK) resources[TestCultures.zh_HK].AddDisplay(e.Name, e.Zh_HK);
            if (e.Zh != e.Zh_TW) resources[TestCultures.zh_TW].AddDisplay(e.Name, e.Zh_TW);
        }
        resources.Should().HaveCount(13);

        LogDeltas(resources, Supported);

        foreach (var resource in resources)
        {
            resource.Value.Data.Sort();
        }

        resources.Save(new("../../../../../src/Qowaiv/Globalization"), "CountryLabels");

        static void LogDeltas(XResourceCollection resources, CultureInfo[] cultures)
        {
            foreach (var country in Country.All)
            {
                foreach (var culture in cultures)
                {
                    var curr = country.GetDisplayName(culture);
                    var next = resources.Display(culture, country);

                    if (curr != next)
                        Console.WriteLine($"{country.Name}[{culture.Name}]: {next} != {curr}");
                }
            }
        }
    }

    [Test]
    public void Data()
    {
        using var reader = new FileInfo("../../../../../Countries.md").OpenText();

        var entries = CountryEntry.Read(reader).ToArray();

        var settings = new CSharpWriterSettings();
        using var file = new StreamWriter("../../../../../src/Qowaiv/Generated/Globalization/CountryData.generated.cs", settings.Encoding, new() { Access = FileAccess.Write, Mode = FileMode.Create });
        var writer = new CSharpWriter(file, settings);

        writer.Write(Headers.AutoGenerated([]));

        using (writer.NamespaceDeclaration("Qowaiv.Globalization"))
        {
            writer.Line("internal sealed partial record CountryData");
            using (writer.CodeBlock())
            {
                writer.Indent().Write("public static readonly CountryLookup<CountryData> All = Init");
                using (writer.CodeBlock("();"))
                {
                    foreach (var entry in entries)
                    {
                        writer.Indent().Write($"""new(Country.{entry.Name}, "{entry.Iso2}", "{entry.Iso3}", {entry.Iso:000}, {(entry.Independent ? 'Y' : 'N')}, new({entry.StartDate:yyyy, MM, dd})""");

                        if (entry.EndDate is { } enddate)
                            writer.Line($", new({enddate:yyyy, MM, dd})),");
                        else
                            writer.Line("),");

                    }
                    writer.Indent().Line("""new(Country.Empty, "", "", 000, N, new(0001, 01, 01)),""");
                    writer.Indent().Line("""new(Country.Unknown, "ZZ", "ZZZ", 999, N, new(0001, 01, 01))""");
                }
            }
        }

        entries.Should().NotBeEmpty();
    }

    [Test]
    public void Consts()
    {
        using var reader = new FileInfo("../../../../../Countries.md").OpenText();

        var entries = CountryEntry.Read(reader).ToArray();

        var settings = new CSharpWriterSettings();
        using var file = new StreamWriter("../../../../../src/Qowaiv/Generated/Globalization/Country.consts.generated.cs", settings.Encoding, new() { Access = FileAccess.Write, Mode = FileMode.Create });
        var writer = new CSharpWriter(file, settings);

        writer.Write(Headers.AutoGenerated([]));
        using (writer.NamespaceDeclaration("Qowaiv.Globalization"))
        {
            writer.Line("public readonly partial struct Country");

            using (writer.CodeBlock())
            {
                foreach (var c in entries)
                {
                    writer.Indent().Line($"/// <summary>Describes the country {c.En} ({c.Name}).</summary>");

                    if (c.EndDate is { } enddate)
                        writer.Indent().Line($"/// <remarks>End date is {enddate:yyyy-MM-dd}.</remarks>.");

                    writer.Indent().Line($"""public static readonly Country {c.Name} = new("{c.Name}");""")
                        .Line();
                }

                writer.Indent().Line("/// <summary>Gets a collection of all countries.</summary>");
                writer.Indent().Write("public static readonly System.Collections.ObjectModel.ReadOnlyCollection<Country> All = new([");
                writer.Write(string.Join(',', entries.Select(c => c.Name)));
                writer.Line("]);");
            }
        }

        entries.Should().NotBeEmpty();
    }

    private sealed record CountryEntry
    {
        public required string Name { get; init; }
        public required string Iso2 { get; init; }
        public required string Iso3 { get; init; }
        public required int Iso { get; init; }
        public required bool Independent { get; init; }
        public required Date StartDate { get; init; }
        public required Date? EndDate { get; init; }
        public required string En { get; init; }
        public required string De { get; init; }
        public required string Es { get; init; }
        public required string Fr { get; init; }
        public required string It { get; init; }
        public required string Nl { get; init; }
        public required string Pt { get; init; }
        public required string Ru { get; init; }
        public required string Ja { get; init; }
        public required string Zh { get; init; }
        public required string Zh_HK { get; init; }
        public required string Zh_TW { get; init; }
        public required string Ar { get; init; }

        public static IEnumerable<CountryEntry> Read(StreamReader reader)
        {
            while (reader.ReadLine() is { } line)
                if (TryParse(line) is { } entry) yield return entry;
        }

        public static CountryEntry? TryParse(string line)
        {
            if (line.Length > 0
               && line[1..].Split('|', StringSplitOptions.TrimEntries) is { Length: > 8 } parts
               && IsName(parts[0]))
            {
                var (name, iso2, iso3, num, i, start, end, en, de, es, fr, it, nl, pt, ru, ja, zh, zh_HK, zh_TW, ar)
                    = (parts[0], parts[1], parts[2], parts[3], parts[4], parts[5], parts[6], parts[7], parts[8], parts[9], parts[10], parts[11], parts[12], parts[13], parts[14], parts[15], parts[16], parts[17], parts[18], parts[19]);

                return new()
                {
                    Name = name,
                    Iso2 = iso2,
                    Iso3 = iso3,
                    Iso = int.TryParse(num, out var iso) ? iso : 0,
                    Independent = i == "Y",
                    StartDate = Date.TryParse(start) ?? Date.MinValue,
                    EndDate = Date.TryParse(end),
                    En = en,
                    De = de,
                    Es = es,
                    Fr = fr,
                    It = it,
                    Nl = nl,
                    Pt = pt,
                    Ru = ru,
                    Ja = ja,
                    Zh = zh,
                    Zh_HK = zh_HK,
                    Zh_TW = zh_TW,
                    Ar = ar,
                };

            }
            else return null;
        }

        private static bool IsName(string s) => s.Length is 2 or 4 && s.All(char.IsAsciiLetterUpper);
    }
}

file static class Extensions
{
    extension(XResourceFile file)
    {
        public void AddDisplay(string name, string val)
            => file.AddKey(name, "DisplayName", val);

        public void AddKey(string name, string key, string val)
            => file.Add($"{name}_{key}", val);
    }
    extension(XResourceCollection files)
    {
        public string? Display(CultureInfo culture, Country country)
            => files.TryGetValue($"{country.Name}_DisplayName", culture);
    }
}
